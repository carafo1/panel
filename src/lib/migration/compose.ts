/**
 * Container configuration for imported sites.
 * ==========================================
 *
 * Pure generators, kept out of `runner.ts` so they can be exercised without
 * dragging in Prisma, ssh2, and the deployer.
 *
 * The compose file and the config files it mounts MUST be generated together:
 * Docker's response to a missing bind source is to create a *directory* at
 * that path, so a compose file referencing a config nobody wrote produces a
 * container that starts and immediately dies with an unhelpful error. The
 * `bindSources` invariant is covered in tests/unit/migration.test.ts.
 */

const DOCKER_NETWORK = process.env.DOCKER_NETWORK || 'deployhub'

export interface ImportComposeOptions {
  stack: string
  containerName: string
  externalPort: number
  documentRoot: string | null
  cpuCores?: number | null
  ramMB?: number | null
}

/**
 * docker-compose for a site we serve straight from an official image.
 *
 * The site tree is mounted from `<deployPath>/site` rather than `<deployPath>`
 * so the compose file, php.ini, and rollback snapshots are never inside the
 * document root — otherwise `docker-compose.yml` would be downloadable from
 * the live website.
 */
export function generateImportCompose(opts: ImportComposeOptions): string {
  const limits =
    opts.cpuCores || opts.ramMB
      ? `    deploy:
      resources:
        limits:
${opts.cpuCores ? `          cpus: '${opts.cpuCores}'\n` : ''}${opts.ramMB ? `          memory: ${opts.ramMB}M\n` : ''}`
      : ''

  if (opts.stack === 'static') {
    return `# Generated by APSAMO Panel — imported static site
services:
  web:
    image: nginx:alpine
    container_name: ${opts.containerName}
    restart: unless-stopped
    ports:
      - "${opts.externalPort}:80"
    volumes:
      - ./site:/site:ro
      # Written by the configure stage. If this file is missing, Docker
      # silently creates a DIRECTORY at the mount point and nginx exits — so
      # the two must always be generated together.
      - ./nginx.conf:/etc/nginx/conf.d/default.conf:ro
${limits}    networks:
      - default
      - ${DOCKER_NETWORK}

networks:
  ${DOCKER_NETWORK}:
    external: true
`
  }

  // WordPress and generic PHP both run on the Apache image. The WordPress
  // image is used for WP because its entrypoint wires up the standard
  // environment and leaves an existing install untouched.
  const image = opts.stack === 'wordpress' ? 'wordpress:php8.2-apache' : 'php:8.2-apache'
  return `# Generated by APSAMO Panel — imported ${opts.stack} site
services:
  web:
    image: ${image}
    container_name: ${opts.containerName}
    restart: unless-stopped
    ports:
      - "${opts.externalPort}:80"
    volumes:
      # The customer's full site tree, including their core files, drop-ins,
      # and root-level assets. The image's entrypoint detects an existing
      # install and leaves it alone.
      - ./site:/var/www/html
      - ./php.ini:/usr/local/etc/php/conf.d/zz-apsamo.ini:ro
${limits}    networks:
      - default
      - ${DOCKER_NETWORK}

networks:
  ${DOCKER_NETWORK}:
    external: true
`
}

/**
 * nginx config for an imported static site.
 *
 * `try_files … /index.html` is what makes a single-page app work: without it
 * every deep link (/about, /products/42) 404s because no such file exists on
 * disk, which is the classic "it works locally but every refresh breaks"
 * report. A plain HTML site is unaffected by the fallback.
 */
export function generateStaticNginxConf(documentRoot: string | null): string {
  const root = documentRoot ? `/site/${documentRoot.replace(/^\/+|\/+$/g, '')}` : '/site'
  return `# Generated by APSAMO Panel — imported static site
server {
    listen 80;
    server_name _;
    root ${root};
    index index.html index.htm;

    location / {
        try_files $uri $uri/ /index.html;
    }

    # Long-lived caching for fingerprinted assets, none for the entry point,
    # so a redeploy is picked up immediately instead of serving a stale shell.
    location ~* \\.(js|css|png|jpg|jpeg|gif|svg|woff2?|ico)$ {
        expires 30d;
        add_header Cache-Control "public, immutable";
    }
    location = /index.html {
        add_header Cache-Control "no-cache";
    }

    gzip on;
    gzip_types text/plain text/css application/json application/javascript text/xml application/xml image/svg+xml;
    gzip_min_length 1024;
}
`
}
